void smdlKelvinToChromaticity(float kelvin, float2 *xy) {
  if (!xy) return;
  // This is the daylight locus defined in CIE 15, which is only valid for
  // temperatures between 4000K and 25000K.
  const float T{std::min(std::max(kelvin, 4000.0f), 25000.0f)};
  const float R{1e3f / T};
  const float x{
      T <= 7000.0f
          ? 0.244063f + 0.09911f * R + 2.9678f * R * R - 4.6070f * R * R * R
          : 0.237040f + 0.24748f * R + 1.9018f * R * R - 2.0064f * R * R * R};
  const float y{-3.000f * x * x + 2.870f * x - 0.275f};
  (*xy)[0] = x;
  (*xy)[1] = y;
}

