/// Phase-only pieces of the evaluation, shared by all anchors
struct PhaseBasis {
  double gr, phi, e1, e2, c3, fade;
};

inline PhaseBasis MakePhaseBasis(double phaseDeg) {
  const double gd = std::abs(phaseDeg);
  const double s =
      std::clamp((kFadeEndDeg - gd) / (kFadeEndDeg - kFadeStartDeg), 0.0, 1.0);
  return {
      gd * kDegToRad,
      phaseDeg * kDegToRad,
      std::exp(-gd / kP1),
      std::exp(-gd / kP2),
      // NOTE: the quotient (g_deg - p3)/p4 is dimensionless and is fed
      // to cos() as RADIANS (no conversion) -- matches rimopy and GIRO.
      std::cos((gd - kP3) / kP4),
      s * s * (3.0 - 2.0 * s),
  };
}

/// Faded disk-equivalent reflectance at anchor k
inline double AnchorReflectance(const PhaseBasis &pb, std::size_t k) {
  const double *c = kCoeffs[k];
  const double phi2 = pb.phi * pb.phi;
  const double lnA = c[0] + pb.gr * (c[1] + pb.gr * (c[2] + pb.gr * c[3])) +
                     pb.phi * (c[4] + phi2 * (c[5] + phi2 * c[6])) +
                     c[7] * pb.e1 + c[8] * pb.e2 + c[9] * pb.c3;
  return pb.fade * std::exp(lnA);
}

