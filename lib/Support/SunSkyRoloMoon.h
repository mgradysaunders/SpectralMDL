/// Lunar-to-solar irradiance multiplier at an arbitrary wavelength
/// (clamped to [0.35, 2.5] um).
///
///  \param wavelengthUm  wavelength [um]
///  \param phaseDeg      signed lunar phase angle [deg]; 0 = full moon,
///                       +/-180 = new moon, sign = waxing/waning branch
///  \param distanceScale (1 AU / d_sun_moon)^2 * (384400 km / d_obs_moon)^2
inline double MoonMultiplier(double wavelengthUm, double phaseDeg,
                             double distanceScale = 1.0) {
  using namespace detail;
  const double wlNm = std::clamp(wavelengthUm * 1000.0, kAnchorNm[0],
                                 kAnchorNm[kAnchorCount - 1]);
  std::size_t lo = 0;
  for (std::size_t k = kAnchorCount - 1; k > 0; --k) {
    if (kAnchorNm[k] <= wlNm) {
      lo = k;
      break;
    }
  }
  lo = std::min(lo, kAnchorCount - 2);
  const double weight =
      (wlNm - kAnchorNm[lo]) / (kAnchorNm[lo + 1] - kAnchorNm[lo]);
  const PhaseBasis pb = MakePhaseBasis(phaseDeg);
  const double a0 = AnchorReflectance(pb, lo);
  const double a1 = AnchorReflectance(pb, lo + 1);
  return (kOmegaMoon / 3.141592653589793) * distanceScale *
         (a0 + (a1 - a0) * weight);
}

/// Multiplier on the sun-sky model's wavelength grid (0.4-2.5 um in
/// 0.005 um steps); parameters as in MoonMultiplier.
inline std::array<float, kSpectrumSize>
EvaluateMoonMultiplier(double phaseDeg, double distanceScale = 1.0) {
  using namespace detail;
  const PhaseBasis pb = MakePhaseBasis(phaseDeg);
  double anchors[kAnchorCount];
  for (std::size_t k = 0; k < kAnchorCount; ++k) {
    anchors[k] = AnchorReflectance(pb, k);
  }
  const double scale = (kOmegaMoon / 3.141592653589793) * distanceScale;
  std::array<float, kSpectrumSize> m;
  for (std::size_t i = 0; i < kSpectrumSize; ++i) {
    const std::size_t lo = kChannelAnchor[i];
    const double a0 = anchors[lo];
    const double a1 = anchors[lo + 1];
    m[i] = static_cast<float>(scale * (a0 + (a1 - a0) * kChannelWeight[i]));
  }
  return m;
}

