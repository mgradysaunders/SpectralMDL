// ROLO lunar-to-solar irradiance multiplier m(wl, g) = E_moon / E_sun,
// dimensionless, for turning the sun-sky model into moonlight:
//   sky radiance = sky model at the moon's direction x m
//   direct moon beam = direct sun beam x m
//
// Model: disk-integrated lunar reflectance of Kieffer & Stone 2005
// (AJ 129, 2887, Eq. 10), zero libration, signed phase angle driving the
// waxing/waning b-polynomial. Coefficients: K&S Table 4 digitized in
// GOA-UVa/rimopy, with the per-band Apollo adjustment (K&S Sec. 3.4)
// folded into a0; the anomalous 2126.3 nm band rebuilt by wavelength
// interpolation of its neighbors; a synthetic 2500 nm anchor extrapolated
// from the 2250.9/2383.6 nm rows. Multiplier m = (Omega_M / pi) * A *
// distanceScale, Omega_M = 6.4177e-5 sr at mean distances; distanceScale
// = (1 AU / d_sun_moon)^2 * (384400 km / d_obs_moon)^2 (+/-14% over the
// anomalistic month from the observer term alone).
//
// Phase convention: g = 0 full moon, |g| = 180 new moon; the sign selects
// waxing vs waning (a 4-13% effect). The ROLO fit spans |g| <= 97 deg;
// beyond that the (monotone, well-behaved) polynomial extrapolates, and a
// smoothstep fade over |g| in [150, 180] deg takes the multiplier to
// exactly zero at new moon.

